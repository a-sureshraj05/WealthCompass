import React, { useState, useEffect } from 'react';
import BrandLogo from './BrandLogo';

interface Props {
  onLogin: () => void;
}

interface InstanceStatus {
  registered: boolean;
  registration_open: boolean;
  demo: boolean;
}

const LoginPage: React.FC<Props> = ({ onLogin }) => {
  const [isRegistering, setIsRegistering] = useState(false);
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [inviteCode, setInviteCode] = useState('');
  const [error, setError] = useState('');
  const [loading, setLoading] = useState(false);
  const [instance, setInstance] = useState<InstanceStatus | null>(null);
  // Set only right after a successful registration — holds the UI on the
  // "save this now" panel below until the user explicitly continues.
  // Registration is server-side, the recovery key is real and already
  // generated by the time this is set; this just blocks the app from
  // rendering until it's acknowledged.
  const [recoveryKey, setRecoveryKey] = useState<string | null>(null);
  const [confirming, setConfirming] = useState(false);

  // Unauthenticated. Its only remaining job is the registration policy below —
  // the demo banner and the credential shortcuts it used to drive were removed
  // deliberately, so the login page carries no demo labelling at all.
  // Failure is non-fatal: the form still works.
  useEffect(() => {
    fetch('/api/v1/auth/status')
      .then(res => (res.ok ? res.json() : null))
      .then(setInstance)
      .catch(() => setInstance(null));
  }, []);

  // Default true so the toggle doesn't flicker out and back while /auth/status
  // is still in flight on a normal instance.
  const registrationOpen = instance ? instance.registration_open : true;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      if (isRegistering) {
        const res = await fetch('/api/v1/auth/register', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ email, password, invite_code: inviteCode }),
        });
        if (!res.ok) {
          const data = await res.json().catch(() => ({}));
          throw new Error(data.detail || 'Registration failed');
        }
        const data = await res.json();
        // The session cookie is already set by this response — registering
        // logs you in. But don't call onLogin() yet: the recovery key is
        // generated once, right now, and never shown again. Hold on this
        // screen until it's explicitly acknowledged.
        setRecoveryKey(data.recovery_key);
      } else {
        const form = new URLSearchParams();
        form.append('username', email);
        form.append('password', password);
        const res = await fetch('/api/v1/auth/login', {
          method: 'POST',
          headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
          body: form.toString(),
        });
        if (!res.ok) {
          const data = await res.json().catch(() => ({}));
          throw new Error(data.detail || 'Incorrect email or password');
        }
        onLogin();
      }
    } catch (err: any) {
      setError(err.message);
    } finally {
      setLoading(false);
    }
  };

  const handleRecoveryKeyConfirmed = async () => {
    setConfirming(true);
    try {
      await fetch('/api/v1/auth/confirm-recovery-key', { method: 'POST' });
    } finally {
      setConfirming(false);
      onLogin();
    }
  };

  // h-full + its own scroll: the body no longer scrolls, so a viewport too
  // short for the card (phone in landscape) would otherwise clip it.
  return (
    <div className="h-full overflow-y-auto bg-slate-50 flex items-center justify-center p-4">
      <div className="w-full max-w-md">
        {/* Logo / App name */}
        <div className="text-center mb-8">
          <h1><BrandLogo size={48} className="login-brand" /></h1>
          <p className="text-sm text-slate-500 mt-4">Your personal portfolio tracker</p>
        </div>

        {/* Card */}
        <div className="bg-white rounded border shadow-sm p-8">
          {recoveryKey ? (
            <>
              <h2 className="text-lg font-bold text-slate-900 mb-2">Save your recovery key</h2>
              <p className="text-xs text-slate-500 mb-4">
                This is shown once, right now. If you ever forget your password, this key is the
                only way back into your account — without it, your data is unrecoverable.
              </p>
              <div className="mb-4 p-3 rounded-md bg-slate-50 border border-slate-200">
                <code className="block text-sm font-mono text-slate-900 break-all select-all">{recoveryKey}</code>
              </div>
              <button
                type="button"
                disabled={confirming}
                onClick={handleRecoveryKeyConfirmed}
                className="w-full py-2.5 bg-[#0F52BA] text-white text-sm font-bold rounded-md hover:bg-[#0A3E8F] transition-colors disabled:opacity-60"
              >
                {confirming ? 'Please wait…' : "I've saved it — Continue"}
              </button>
            </>
          ) : (
          <>
          <h2 className="text-lg font-bold text-slate-900 mb-6">
            {isRegistering ? 'Create your account' : 'Sign in to your account'}
          </h2>

          <form onSubmit={handleSubmit} className="space-y-4">
            <div>
              <label className="block text-xs font-black text-slate-500 uppercase tracking-widest mb-1.5">Email</label>
              <input
                type="email"
                value={email}
                onChange={e => setEmail(e.target.value)}
                required
                placeholder="you@example.com"
                className="w-full px-4 py-2.5 rounded-md border border-slate-200 text-sm text-slate-900 placeholder-slate-300 focus:outline-none focus:ring-2 focus:ring-[#0F52BA] focus:border-transparent"
              />
            </div>

            <div>
              <label className="block text-xs font-black text-slate-500 uppercase tracking-widest mb-1.5">Password</label>
              <input
                type="password"
                value={password}
                onChange={e => setPassword(e.target.value)}
                required
                placeholder="••••••••"
                className="w-full px-4 py-2.5 rounded-md border border-slate-200 text-sm text-slate-900 placeholder-slate-300 focus:outline-none focus:ring-2 focus:ring-[#0F52BA] focus:border-transparent"
              />
            </div>

            {isRegistering && (
              <div>
                <label className="block text-xs font-black text-slate-500 uppercase tracking-widest mb-1.5">Invite code</label>
                <input
                  type="text"
                  value={inviteCode}
                  onChange={e => setInviteCode(e.target.value)}
                  required
                  placeholder="Enter your invite code"
                  className="w-full px-4 py-2.5 rounded-md border border-slate-200 text-sm text-slate-900 placeholder-slate-300 focus:outline-none focus:ring-2 focus:ring-[#0F52BA] focus:border-transparent"
                />
              </div>
            )}

            {error && (
              <p className="text-xs font-bold text-rose-600 bg-rose-50 px-3 py-2 rounded">{error}</p>
            )}

            <button
              type="submit"
              disabled={loading}
              className="w-full py-2.5 bg-[#0F52BA] text-white text-sm font-bold rounded-md hover:bg-[#0A3E8F] transition-colors disabled:opacity-60"
            >
              {loading ? 'Please wait…' : isRegistering ? 'Create Account' : 'Sign In'}
            </button>
          </form>

          {/* Offering a signup link the server will reject with a 403 is worse
              than offering nothing, so the toggle follows the server's policy. */}
          {registrationOpen && (
            <div className="mt-6 text-center">
              {isRegistering ? (
                <p className="text-xs text-slate-500">
                  Already have an account?{' '}
                  <button onClick={() => { setIsRegistering(false); setError(''); }} className="text-[#0F52BA] font-bold hover:underline">Sign in</button>
                </p>
              ) : (
                <p className="text-xs text-slate-500">
                  First time here?{' '}
                  <button onClick={() => { setIsRegistering(true); setError(''); }} className="text-[#0F52BA] font-bold hover:underline">Create account</button>
                </p>
              )}
            </div>
          )}
          </>
          )}
        </div>
      </div>
    </div>
  );
};

export default LoginPage;
