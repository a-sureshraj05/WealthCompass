import React, { useState, useEffect, useCallback, useRef } from 'react';
import type { StockHolding } from '../../types';
import { fetchInsightsCached, generateInsights } from '../../services/apiService';
import AIChat from './AIChat';
import InsightsPanel, { insightLines } from './Insights/InsightsPanel';
import PreviewInsights from '../../preview/PreviewInsights';

interface Props {
  holdings: StockHolding[];
  cashByBrokerage: Record<string, number>;
  refreshNonce?: number;
  preview?: boolean;
  numbersVisible?: boolean;
  scopeFiltered?: boolean;
  onOpenHoldings: (ticker?: string) => void;
  onOpenGains: () => void;
}

type LiveProps = Props & { numbersVisible: boolean; scopeFiltered: boolean; };

function LiveInsights({ holdings, refreshNonce = 0, numbersVisible, scopeFiltered, onOpenHoldings, onOpenGains }: LiveProps) {
  const [insights, setInsights] = useState('');
  const [generatedAt, setGeneratedAt] = useState<number | null>(null);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [stale, setStale] = useState(false);
  const [error, setError] = useState('');
  const [chatOpen, setChatOpen] = useState(false);
  const autoGenerated = useRef(false);
  const inFlight = useRef(false);
  const generationVersion = useRef(0);
  const mounted = useRef(true);

  useEffect(() => { mounted.current = true; return () => { mounted.current = false; }; }, []);

  const handleGenerate = useCallback(async () => {
    if (inFlight.current) return;
    inFlight.current = true;
    generationVersion.current++;
    setGenerating(true);
    setError('');
    try {
      const data = await generateInsights();
      if (!mounted.current) return;
      if (data.available === false) setError(data.reason || 'Insights are unavailable.');
      else { setInsights(data.text || ''); setGeneratedAt(data.generated_at); setStale(data.stale); }
    } catch (error) {
      if (mounted.current) setError(error instanceof Error ? error.message : 'Could not generate insights.');
    } finally {
      inFlight.current = false;
      if (mounted.current) setGenerating(false);
    }
  }, []);

  // Preserve the existing cache-first workflow and at most one stale-cache
  // generation per mount. The preview mounts a separate, entirely local view.
  useEffect(() => {
    let cancelled = false;
    const version = generationVersion.current;
    if (!holdings.length) { setInsights(''); setLoading(false); return; }
    void fetchInsightsCached().then(data => {
      if (cancelled || version !== generationVersion.current) return;
      setInsights(data.text || '');
      setGeneratedAt(data.generated_at);
      setStale(data.stale);
      if (data.available === false) setError(data.reason || 'Insights are unavailable.');
      else if (data.stale && !autoGenerated.current) { autoGenerated.current = true; void handleGenerate(); }
    }).catch(() => {
      if (!cancelled) setError('Could not load cached insights. Try updating insights.');
    }).finally(() => { if (!cancelled) setLoading(false); });
    return () => { cancelled = true; };
  }, [holdings.length, handleGenerate]);

  // An explicit portfolio refresh retains its existing regeneration behavior.
  const lastRefresh = useRef(refreshNonce);
  useEffect(() => {
    if (refreshNonce === lastRefresh.current) return;
    lastRefresh.current = refreshNonce;
    if (holdings.length > 0) void handleGenerate();
  }, [refreshNonce, holdings.length, handleGenerate]);

  const items = holdings.length ? insightLines(insights).map((text, index) => ({ title: `Observation ${index + 1}`, text })) : [];
  return <InsightsPanel items={items} loading={loading} generating={generating} stale={stale} error={error}
    hasHoldings={holdings.length > 0} numbersVisible={numbersVisible} scopeFiltered={scopeFiltered} generatedAt={generatedAt}
    onGenerate={() => void handleGenerate()} onAsk={() => setChatOpen(true)}
    onOpenHoldings={() => onOpenHoldings()} onOpenGains={onOpenGains}>
    {chatOpen && numbersVisible && <AIChat open onClose={() => setChatOpen(false)} />}
  </InsightsPanel>;
}

export default function AIInsights({ preview = false, numbersVisible = true, scopeFiltered = false, ...props }: Props) {
  if (import.meta.env.DEV && preview) return <PreviewInsights {...props} numbersVisible={numbersVisible} scopeFiltered={scopeFiltered} />;
  return <LiveInsights {...props} numbersVisible={numbersVisible} scopeFiltered={scopeFiltered} />;
}
